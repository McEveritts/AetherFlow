pub fn is_demo_mode_active() -> bool {
    if af_services::is_streaming_demo_mode() {
        return true;
    }
    env::var("AETHERFLOW_DEMO_MODE")
        .ok()
        .map(|v| matches!(v.trim().to_lowercase().as_str(), "1" | "true" | "yes"))
        .unwrap_or(false)
}

